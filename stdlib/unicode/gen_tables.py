# Writes tables.go: the rune ranges of Unicode categories L (letters),
# N (numbers), Nd (decimal digits), Lu and Ll, from Python's unicodedata.
#
#   python -I stdlib/unicode/gen_tables.py > stdlib/unicode/tables.go
import sys
import unicodedata


def ranges(pred):
    out = []
    lo = None
    for cp in range(sys.maxunicode + 1):
        if pred(chr(cp)):
            if lo is None:
                lo = cp
            hi = cp
        elif lo is not None:
            out.append((lo, hi))
            lo = None
    if lo is not None:
        out.append((lo, hi))
    return out


def emit(name, rs):
    print("var %s = []int32{" % name)
    line = "\t"
    for lo, hi in rs:
        item = "%d, %d, " % (lo, hi)
        if len(line) + len(item) > 96:
            print(line.rstrip())
            line = "\t"
        line += item
    if line.strip():
        print(line.rstrip())
    print("}")
    print()


cat = unicodedata.category
print("// Code generated by gen_tables.py from Python unicodedata %s. DO NOT EDIT." % unicodedata.unidata_version)
print()
print("package unicode")
print()
print("// Each table is sorted [lo, hi] pairs of inclusive rune ranges.")
print()
emit("letterRanges", ranges(lambda c: cat(c).startswith("L")))
emit("numberRanges", ranges(lambda c: cat(c).startswith("N")))
emit("digitRanges", ranges(lambda c: cat(c) == "Nd"))
emit("upperRanges", ranges(lambda c: cat(c) == "Lu"))
emit("lowerRanges", ranges(lambda c: cat(c) == "Ll"))
