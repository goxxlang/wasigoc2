// Compile ieda.gml with guikit onto an rmlui context and write ieda.html.
// The page is that element tree. ieda.js talks to HeapVM.
//
//	goclang++.bat main.go -o ieda.exe --no-shim-sandbox
//	ieda.exe > ieda.html
package main

import (
	"fmt"
	"guikit"
	"os"
	"rmlui"
	"strings"
)

var boundIds = []string{
	"status", "nav-vm", "nav-eda", "view-vm", "view-eda",
	"hv-run", "wsl-status", "wsl-list", "wsl-boot", "vm-out",
	"eda-refresh", "designs", "fmt", "emit", "check", "download",
	"f-name", "f-lut", "f-pe", "f-reg", "f-rom", "f-emit", "f-what",
	"blif-path", "import", "eda-out", "eda-src", "vgpu",
	"nav-si", "view-si", "si-heading", "si-blurb", "si-err",
	"si-card-pipe", "si-pipe-img", "si-card-spi", "si-spi-img",
	"si-card-slack", "si-slack", "si-facts",
	"si-card-power", "si-power", "si-card-skew", "si-skew",
	"nav-time", "view-time", "time-heading", "time-blurb", "time-err",
	"time-chip", "time-corner", "time-kind", "time-load",
	"time-card-sum", "time-sum", "time-card-paths", "time-rows", "time-detail",
}

func main() {
	f, oerr := os.Open("ieda.gml")
	if oerr != nil {
		fmt.Fprintln(os.Stderr, "open", oerr)
		os.Exit(1)
	}
	buf := make([]byte, 1<<20)
	n, _ := f.Read(buf)
	src := string(buf[:n])

	quiet := rmlui.NewDefaultSystemInterface()
	quiet.Quiet = true
	rmlui.SetSystemInterface(quiet)
	rmlui.Initialise()
	ctx := rmlui.CreateContext("ieda", rmlui.Vector2i{1440, 900})
	doc, err := guikit.Load(ctx, src)
	if err != nil || doc == nil {
		fmt.Fprintln(os.Stderr, "load", err)
		os.Exit(1)
	}
	for i := 0; i < len(boundIds); i++ {
		if doc.GetElementById(boundIds[i]) == nil {
			fmt.Fprintln(os.Stderr, "missing #"+boundIds[i])
			os.Exit(1)
		}
	}

	css := extractBlock(src, "style")
	if !strings.Contains(css, "section.view") {
		fmt.Fprintln(os.Stderr, "style block dropped inner rules")
		os.Exit(1)
	}
	fmt.Print("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\"/>\n")
	fmt.Print("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\"/>\n")
	fmt.Print("<title>Encryptid iEDA</title>\n")
	fmt.Print("<!-- generated by main.go from ieda.gml (guikit + rmlui); edit ieda.gml -->\n<style>\n")
	fmt.Print(css)
	fmt.Print("\n</style>\n</head>\n<body>\n")
	root := doc.GetElement()
	count := root.GetNumChildren(false)
	for i := 0; i < count; i++ {
		emit(root.GetChild(i))
		fmt.Print("\n")
	}
	fmt.Print("<script type=\"module\" src=\"/ieda/ieda.js\"></script>\n</body>\n</html>\n")
}

var voidTags = map[string]bool{"input": true, "img": true, "br": true, "hr": true, "meta": true}

func emit(el *rmlui.Element) {
	if el == nil {
		return
	}
	if el.GetTagName() == "#text" {
		text := rmlui.ElementTextOf(el)
		if text != nil {
			fmt.Print(escape(text.GetText()))
		}
		return
	}
	tag := el.GetTagName()
	if tag == "" {
		tag = "div"
	}
	fmt.Print("<" + tag)
	names := el.GetAttributeNames()
	sortStrings(names)
	for i := 0; i < len(names); i++ {
		name := names[i]
		if name == "onclick" || name == "onsubmit" || name == "onchange" {
			continue
		}
		value := el.GetAttributeString(name, "")
		if value == "true" && (name == "selected" || name == "checked" || name == "disabled") {
			fmt.Print(" " + name)
			continue
		}
		fmt.Print(" " + name + "=\"" + escape(value) + "\"")
	}
	fmt.Print(">")
	if voidTags[tag] {
		return
	}
	n := el.GetNumChildren(false)
	for i := 0; i < n; i++ {
		emit(el.GetChild(i))
	}
	fmt.Print("</" + tag + ">")
}

func sortStrings(a []string) {
	for i := 1; i < len(a); i++ {
		for j := i; j > 0 && a[j] < a[j-1]; j-- {
			a[j], a[j-1] = a[j-1], a[j]
		}
	}
}

func escape(s string) string {
	s = strings.ReplaceAll(s, "&", "&amp;")
	s = strings.ReplaceAll(s, "<", "&lt;")
	s = strings.ReplaceAll(s, ">", "&gt;")
	s = strings.ReplaceAll(s, "\"", "&quot;")
	return s
}

func extractBlock(src string, word string) string {
	i := strings.Index(src, word+" {")
	if i < 0 {
		return ""
	}
	start := i + len(word) + 1
	depth := 0
	for k := start; k < len(src); k++ {
		if src[k] == '{' {
			depth++
		}
		if src[k] == '}' {
			depth--
			if depth == 0 {
				return src[start+1 : k]
			}
		}
	}
	return ""
}
