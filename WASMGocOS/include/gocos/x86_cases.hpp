inline uint64_t Pick(std::mt19937_64& rng) {
  static const uint64_t kEdge[] = {0, 1, 2, 0x7f, 0x80, 0xff, 0x7fff, 0x8000, 0xffff,
                                   0x7fffffff, 0x80000000, 0xffffffff, 0x100000000ull,
                                   0x7fffffffffffffffull, 0x8000000000000000ull, ~0ull, 63, 64};
  switch (rng() % 4) {
    case 0: return kEdge[rng() % (sizeof(kEdge) / sizeof(kEdge[0]))];
    case 1: return rng() & 0xff;
    default: return rng();
  }
}

